package codegen

import (
	"bytes"
	"fmt"
	"strings"
)

// renderFile generates the content of a *_datamask.go file.
func renderFile(pkgName string, structs []structInfo) []byte {
	var buf bytes.Buffer

	// Header.
	buf.WriteString("// Code generated by datamask generate; DO NOT EDIT.\n\n")
	buf.WriteString("package " + pkgName + "\n\n")

	// datamask is always needed (compile-time Maskable check); fmt only when
	// a Maskable field's error is wrapped; the package masker only for
	// generic types, which delegate to datamask.Redact.
	needsFmt, needsMasker := false, false
	for _, s := range structs {
		if s.IsGeneric {
			needsMasker = true
			continue
		}
		for _, f := range s.Fields {
			if f.IsMaskable {
				needsFmt = true
			}
		}
	}
	if needsFmt {
		buf.WriteString("import (\n\t\"fmt\"\n\n\t\"github.com/datamaskio/datamask\"\n)\n\n")
	} else {
		buf.WriteString("import \"github.com/datamaskio/datamask\"\n\n")
	}
	if needsMasker {
		buf.WriteString("var _masker = datamask.New()\n\n")
	}

	for _, s := range structs {
		renderStruct(&buf, s)
	}

	return buf.Bytes()
}

// renderStruct generates the Mask() method and compile-time check for one struct.
func renderStruct(buf *bytes.Buffer, s structInfo) {
	typeParams := ""
	typeArgs := ""
	if s.IsGeneric {
		typeParams = "[" + strings.Join(s.TypeParams, ", ") + "]"
		typeArgs = "[" + strings.Join(s.TypeParams, ", ") + "]"
	}

	receiverName := strings.ToLower(s.Name[:1])

	if s.IsGeneric {
		// Generic types: delegate to datamask.Redact.
		buf.WriteString(fmt.Sprintf(
			"func (%s %s%s) Mask() (any, error) {\n"+
				"\tmasked, err := datamask.Redact(_masker, %s)\n"+
				"\tif err != nil {\n"+
				"\t\treturn %s%s{}, err\n"+
				"\t}\n"+
				"\treturn masked, nil\n"+
				"}\n\n",
			receiverName, s.Name, typeParams, receiverName, s.Name, typeArgs,
		))
	} else {
		// Non-generic types: inline masking.
		buf.WriteString(fmt.Sprintf(
			"func (%s %s) Mask() (any, error) {\n",
			receiverName, s.Name,
		))
		for _, f := range s.Fields {
			if f.IsMaskable {
				renderMaskableField(buf, receiverName, s.Name, f)
				continue
			}
			if f.Tag != "" {
				renderTaggedField(buf, receiverName, f)
			}
		}
		buf.WriteString(fmt.Sprintf("\treturn %s, nil\n", receiverName))
		buf.WriteString("}\n\n")
	}

	// Compile-time Maskable check.
	if s.IsGeneric {
		// For generic types, instantiate with string.
		typeArgsConcrete := "[" + strings.Repeat("string, ", len(s.TypeParams))
		typeArgsConcrete = typeArgsConcrete[:len(typeArgsConcrete)-2] + "]"
		buf.WriteString(fmt.Sprintf(
			"var _ datamask.Maskable = %s%s{}\n\n",
			s.Name, typeArgsConcrete,
		))
	} else {
		buf.WriteString(fmt.Sprintf(
			"var _ datamask.Maskable = %s{}\n\n",
			s.Name,
		))
	}
}

// renderTaggedField emits code for a mask-tagged field.
func renderTaggedField(buf *bytes.Buffer, recv string, f fieldInfo) {
	fieldExpr := recv + "." + f.Name

	switch {
	case f.IsPointer:
		buf.WriteString(fmt.Sprintf(
			"\tif %s != nil {\n"+
				"\t\tredacted := \"[REDACTED]\"\n"+
				"\t\t%s = &redacted\n"+
				"\t}\n",
			fieldExpr, fieldExpr,
		))
	default:
		buf.WriteString(fmt.Sprintf(
			"\t%s = \"[REDACTED]\"\n",
			fieldExpr,
		))
	}
}

// renderMaskableField emits fail-closed code for a field whose type
// implements Maskable: a Mask() error or a result of the wrong type returns
// the zero struct wrapped in datamask.ErrMaskFailed, never the unmasked value.
func renderMaskableField(buf *bytes.Buffer, recv, structName string, f fieldInfo) {
	fieldExpr := recv + "." + f.Name
	want := stripPointer(f.FieldType)
	assign := fieldExpr + " = v"
	indent := "\t"
	if f.IsPointer {
		assign = fieldExpr + " = &v"
		indent = "\t\t"
		buf.WriteString(fmt.Sprintf("\tif %s != nil {\n", fieldExpr))
	}
	buf.WriteString(fmt.Sprintf(
		"%[1]sif masked, err := %[2]s.Mask(); err != nil {\n"+
			"%[1]s\treturn %[3]s{}, fmt.Errorf(\"%%w: %[4]s: %%w\", datamask.ErrMaskFailed, err)\n"+
			"%[1]s} else if v, ok := masked.(%[5]s); ok {\n"+
			"%[1]s\t%[6]s\n"+
			"%[1]s} else {\n"+
			"%[1]s\treturn %[3]s{}, fmt.Errorf(\"%%w: %[4]s: Mask() returned %%T, want %[5]s\", datamask.ErrMaskFailed, masked)\n"+
			"%[1]s}\n",
		indent, fieldExpr, structName, f.Name, want, assign,
	))
	if f.IsPointer {
		buf.WriteString("\t}\n")
	}
}

// stripPointer removes the leading "*" from a type expression.
func stripPointer(t string) string {
	return strings.TrimPrefix(t, "*")
}
