// Package codegen generates zero-reflection Redact methods for Go structs.
//
// It walks Go source files via go/ast and go/parser, finds structs with
// mask tags or Maskable fields, and produces *_datamask.go files containing
// generated Mask() methods that satisfy the datamask.Maskable interface.
//
// Usage:
//
//	codegen.Generate("./mypkg")          // generate in package
//	codegen.Generate("./...")            // generate in all packages (CLI)
package codegen

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// Generate walks the Go package at pkgPath and generates *_datamask.go
// files for the structs whose masking is redact-only (ADR-0019). Types it
// cannot generate safely are skipped, with a warning on stderr, and keep
// using the Schema path.
//
// Existing *_datamask.go files are overwritten, and one that no longer has
// anything to generate is removed. Non-Go files and test files are skipped.
func Generate(pkgPath string) error {
	res, err := Analyze(pkgPath)
	if err != nil {
		return err
	}
	for _, w := range res.Warnings {
		fmt.Fprintln(os.Stderr, w)
	}
	for _, stale := range res.Stale {
		if err := os.Remove(stale); err != nil {
			return fmt.Errorf("codegen: remove stale %s: %w", stale, err)
		}
	}
	for _, f := range res.Files {
		if err := os.WriteFile(f.Path, f.Content, 0644); err != nil {
			return fmt.Errorf("codegen: write %s: %w", f.Path, err)
		}
	}
	return nil
}

// GeneratedFile holds the path and content of a generated file.
type GeneratedFile struct {
	Path    string
	Content []byte
}

// Result is the outcome of analyzing a package: the files to write and a
// warning for every type that was skipped.
type Result struct {
	Files    []GeneratedFile
	Warnings []Warning
	// Stale lists previously generated *_datamask.go files that nothing in
	// the package needs any more (for example after a tag changed to hash).
	// Left in place they would keep masking with outdated logic, so Generate
	// removes them and `generate --check` reports them.
	Stale []string
}

// GeneratedFiles returns the files that would be generated for pkgPath
// without writing them. Used by --dry-run. Skipped types are reported by
// Analyze.
func GeneratedFiles(pkgPath string) ([]GeneratedFile, error) {
	res, err := Analyze(pkgPath)
	return res.Files, err
}

// Analyze parses pkgPath and returns the files to generate and the types it
// skipped. A type is generated only when every field is either handled by
// the generated code or has nothing to mask; anything else keeps using the
// Schema path and produces a Warning.
func Analyze(pkgPath string) (Result, error) {
	pkgPath, err := filepath.Abs(pkgPath)
	if err != nil {
		return Result{}, fmt.Errorf("codegen: %w", err)
	}

	fset := token.NewFileSet()
	pkgs, err := parser.ParseDir(fset, pkgPath, goFileFilter, parser.ParseComments)
	if err != nil {
		return Result{}, fmt.Errorf("codegen: parse %s: %w", pkgPath, err)
	}

	var res Result
	for pkgName, pkg := range pkgs {
		structs, warnings := findStructs(pkg)
		res.Warnings = append(res.Warnings, warnings...)
		outPath := filepath.Join(pkgPath, pkgName+"_datamask.go")
		if len(structs) == 0 {
			if isGeneratedFile(outPath) {
				res.Stale = append(res.Stale, outPath)
			}
			continue
		}

		// Sort for deterministic output.
		sort.Slice(structs, func(i, j int) bool {
			return structs[i].Name < structs[j].Name
		})

		res.Files = append(res.Files, GeneratedFile{Path: outPath, Content: renderFile(pkgName, structs)})
	}
	return res, nil
}

// generatedHeader starts every file this package writes.
const generatedHeader = "// Code generated by datamask generate; DO NOT EDIT."

// isGeneratedFile reports whether path exists and was written by the
// generator, so a hand-written file with the same name is never touched.
func isGeneratedFile(path string) bool {
	b, err := os.ReadFile(path)
	return err == nil && strings.HasPrefix(string(b), generatedHeader)
}

// goFileFilter excludes generated files, test files, and non-Go files.
func goFileFilter(fi os.FileInfo) bool {
	name := fi.Name()
	if !strings.HasSuffix(name, ".go") {
		return false
	}
	if strings.HasSuffix(name, "_test.go") {
		return false
	}
	if strings.HasSuffix(name, "_datamask.go") {
		return false
	}
	return true
}

// structInfo holds the information needed to generate a Mask() method.
type structInfo struct {
	Name   string      // Struct name
	Fields []fieldInfo // Fields that need generated code
}

type fieldInfo struct {
	Name       string // Field name
	IsPointer  bool   // True if field is *T
	IsMaskable bool   // True if field type has a Mask() method
	Tag        string // mask tag value, or empty
	FieldType  string // Go type expression (e.g., "string", "EmailMask", "*creditCard")
}

// findStructs walks the AST of a parsed package and returns the structs that
// can be generated, plus a warning for every struct that was skipped.
func findStructs(pkg *ast.Package) ([]structInfo, []Warning) {
	idx := newIndex(pkg)
	var (
		structs  []structInfo
		warnings []Warning
	)
	for _, file := range pkg.Files {
		for _, decl := range file.Decls {
			genDecl, ok := decl.(*ast.GenDecl)
			if !ok || genDecl.Tok != token.TYPE {
				continue
			}
			for _, spec := range genDecl.Specs {
				typeSpec, ok := spec.(*ast.TypeSpec)
				if !ok {
					continue
				}
				structType, ok := typeSpec.Type.(*ast.StructType)
				if !ok {
					continue
				}
				si, warn := idx.analyzeStruct(typeSpec, structType)
				switch {
				case warn != nil:
					// Only warn about types that would otherwise have been
					// generated: a skipped type with nothing to mask is silent.
					if hasMaskingIntent(structType, idx) || strings.Contains(warn.Reason, "nested value") {
						warnings = append(warnings, *warn)
					}
				case len(si.Fields) > 0:
					structs = append(structs, si)
				}
			}
		}
	}
	sortWarnings(warnings)
	return structs, warnings
}

// hasMaskingIntent reports whether the struct carries any mask tag or
// Maskable field, i.e. whether the user would expect a generated Mask().
func hasMaskingIntent(st *ast.StructType, idx *pkgIndex) bool {
	if st.Fields == nil {
		return false
	}
	for _, f := range st.Fields.List {
		if tagOf(f) != "" {
			return true
		}
		if k, _ := idx.classify(f.Type); k == kindMaskable {
			return true
		}
	}
	return false
}

// reflectTag is a minimal struct tag parser mirroring reflect.StructTag.
type reflectTag string

func (t reflectTag) Lookup(key string) (string, bool) {
	v, _ := t.LookupWithDefault(key, "")
	return v, v != ""
}

func (t reflectTag) LookupWithDefault(key, def string) (string, bool) {
	for s := string(t); s != ""; {
		// Skip leading space.
		for len(s) > 0 && s[0] == ' ' {
			s = s[1:]
		}
		if s == "" {
			break
		}
		// Find key.
		i := 0
		for i < len(s) && s[i] > ' ' && s[i] != ':' && s[i] != '"' && s[i] != 0x7f {
			i++
		}
		if i == 0 || i >= len(s) || s[i] != ':' {
			break
		}
		k := s[:i]
		s = s[i+1:]
		if len(s) > 0 && s[0] == '"' {
			j := 1
			for j < len(s) && s[j] != '"' {
				if s[j] == '\\' {
					j++ // skip escaped char
				}
				j++
			}
			if j < len(s) {
				v := s[1:j]
				s = s[j+1:]
				if k == key {
					return v, true
				}
				continue
			}
		}
		// Non-quoted value.
		j := 0
		for j < len(s) && s[j] > ' ' && s[j] != '"' && s[j] != 0x7f {
			j++
		}
		if k == key {
			return s[:j], true
		}
		s = s[j:]
	}
	return def, false
}

// typeExprString converts an AST type expression to a Go type string.
func typeExprString(expr ast.Expr) string {
	switch t := expr.(type) {
	case *ast.Ident:
		return t.Name
	case *ast.StarExpr:
		return "*" + typeExprString(t.X)
	case *ast.SelectorExpr:
		return typeExprString(t.X) + "." + t.Sel.Name
	case *ast.ArrayType:
		if t.Len == nil {
			return "[]" + typeExprString(t.Elt)
		}
		return "[" + typeExprString(t.Len) + "]" + typeExprString(t.Elt)
	case *ast.MapType:
		return "map[" + typeExprString(t.Key) + "]" + typeExprString(t.Value)
	case *ast.BasicLit:
		return t.Value
	case *ast.IndexExpr:
		return typeExprString(t.X) + "[" + typeExprString(t.Index) + "]"
	default:
		return fmt.Sprintf("%T", t)
	}
}
